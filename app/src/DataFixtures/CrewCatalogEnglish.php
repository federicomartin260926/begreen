    public static function department(string $scope, string $spanish): string
    {
        return self::DEPARTMENT_OVERRIDES[self::key($scope, $spanish)]
            ?? self::DEPARTMENTS[$spanish]
            ?? throw new \LogicException(sprintf('Missing English crew department translation for "%s".', $spanish));
    }

    public static function position(string $scope, string $departmentSpanish, string $positionSpanish): string
    {
        return self::POSITION_OVERRIDES[self::key($scope, $departmentSpanish, $positionSpanish)]
            ?? self::POSITIONS[$positionSpanish]
            ?? throw new \LogicException(sprintf(
                'Missing English crew position translation for "%s" in "%s" (%s).',
                $positionSpanish,
                $departmentSpanish,
                $scope
            ));
    }

    private static function key(string ...$parts): string
    {
        return implode('|', $parts);
    }
